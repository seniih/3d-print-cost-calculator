/**
 * Reads print time and filament weight out of what slicers write into their
 * files. Pure text parsing: no I/O, so it is easy to test and runs in the
 * browser, where the file never has to leave the user's machine.
 *
 * Slicers keep this information as comments, in the header (Cura, Bambu
 * Studio, Simplify3D) or the footer (PrusaSlicer, OrcaSlicer, SuperSlicer),
 * so callers pass both ends of a G-code file.
 */

export type FilamentUse = {
  grams: number;
  /** True when the slicer reported length or volume and the weight was worked out from it. */
  estimated: boolean;
};

export type SliceInfo = {
  slicer: string | null;
  /** Print time in seconds, if the file says. */
  printSeconds: number | null;
  /** One entry per filament that was actually used. */
  filaments: FilamentUse[];
};

/** Typical densities in g/cm³, for slicers that only report length or volume. */
const DEFAULT_DENSITY = 1.24; // PLA
const DEFAULT_DIAMETER_MM = 1.75;

const DENSITY: Record<string, number> = {
  PLA: 1.24,
  PETG: 1.27,
  ABS: 1.04,
  ASA: 1.07,
  TPU: 1.21,
  PA: 1.14,
  NYLON: 1.14,
  PC: 1.2,
};

/** "1d 2h 3m 4s", "2h 3m", "12m 5s", "1 hours 2 minutes" → seconds. Null if no unit found. */
export function parseDuration(text: string): number | null {
  const unit = /(\d+(?:\.\d+)?)\s*(days?|d|hours?|hrs?|h|minutes?|mins?|m|seconds?|secs?|s)\b/gi;
  let total = 0;
  let found = false;
  for (const m of text.matchAll(unit)) {
    const n = Number(m[1]);
    const u = m[2].toLowerCase();
    found = true;
    if (u.startsWith("d")) total += n * 86400;
    else if (u.startsWith("h")) total += n * 3600;
    else if (u.startsWith("m")) total += n * 60;
    else total += n;
  }
  return found ? total : null;
}

const list = (text: string) =>
  text
    .split(/[,;]/)
    .map((x) => Number(x.trim()))
    .filter((n) => Number.isFinite(n));

function gramsFromLengthMm(mm: number, density: number, diameter: number) {
  const radius = diameter / 2;
  return ((Math.PI * radius * radius * mm) / 1000) * density; // mm³ → cm³ → g
}

/** First `key = value` style comment in `text`, as the value part. */
function find(text: string, pattern: RegExp): string | null {
  return pattern.exec(text)?.[1]?.trim() ?? null;
}

function detectSlicer(text: string): string | null {
  const checks: [RegExp, string][] = [
    [/;\s*generated by (OrcaSlicer|PrusaSlicer|SuperSlicer|BambuStudio|Bambu Studio|Cura_SteamEngine|Simplify3D|IdeaMaker|ideaMaker)/i, "$1"],
    [/;\s*(BambuStudio|OrcaSlicer)\s+\d/i, "$1"],
    [/;Generated with Cura_SteamEngine/i, "Cura"],
    [/;\s*G-Code generated by Simplify3D/i, "Simplify3D"],
  ];
  for (const [re, name] of checks) {
    const m = re.exec(text);
    if (m) {
      const raw = name === "$1" ? m[1] : name;
      if (/^cura/i.test(raw)) return "Cura";
      if (/^bambu/i.test(raw)) return "Bambu Studio";
      return raw;
    }
  }
  return null;
}

/**
 * Parses the start and the end of a G-code file. Pass the same text twice
 * for a small file. Returns whatever could be read; empty `filaments` and a
 * null time mean the file carries no slicer summary.
 */
export function parseGcode(head: string, tail: string): SliceInfo {
  const text = `${head}\n${tail}`;
  const slicer = detectSlicer(text);

  // --- Time ----------------------------------------------------------------
  let printSeconds: number | null = null;
  const timeSources: (string | null)[] = [
    // PrusaSlicer, OrcaSlicer, SuperSlicer
    find(text, /;\s*estimated printing time \(normal mode\)\s*=\s*([^\r\n]+)/i),
    // Bambu Studio / Orca header: "; model printing time: 1h; total estimated time: 1h 5m"
    find(text, /;[^\r\n]*total estimated time:\s*([^\r\n;]+)/i),
    // Simplify3D
    find(text, /;\s*Build time:\s*([^\r\n]+)/i),
  ];
  for (const src of timeSources) {
    const s = src ? parseDuration(src) : null;
    if (s !== null) {
      printSeconds = s;
      break;
    }
  }
  if (printSeconds === null) {
    // Cura: ";TIME:3600" or ";PRINT.TIME:3600", plain seconds.
    const cura = find(text, /^;(?:PRINT\.)?TIME:\s*(\d+(?:\.\d+)?)/im);
    if (cura !== null) printSeconds = Number(cura);
  }

  // --- Filament weight -----------------------------------------------------
  let filaments: FilamentUse[] = [];
  const types = find(text, /;\s*filament_type\s*[=:]\s*([^\r\n]+)/i)
    ?.split(/[;,]/)
    .map((t) => t.replace(/["']/g, "").trim().toUpperCase());
  const diameters = find(text, /;\s*filament_diameter\s*[=:]\s*([^\r\n]+)/i);
  const densities = find(text, /;\s*(?:filament_density|filament density)\s*[=:]\s*([^\r\n]+)/i);

  // Per filament, in grams. PrusaSlicer, OrcaSlicer, SuperSlicer.
  const perFilament = find(text, /;\s*filament used \[g\]\s*=\s*([^\r\n]+)/i);
  // One total. Bambu Studio / Orca header and footer.
  const totalGrams =
    find(text, /;\s*total filament weight \[g\]\s*:\s*([^\r\n]+)/i) ??
    find(text, /;\s*total filament used \[g\]\s*=\s*([^\r\n]+)/i);
  // Simplify3D: "Plastic weight: 3.48 g ( 0.01 lb )"
  const s3dGrams = find(text, /;\s*Plastic weight:\s*([\d.]+)\s*g/i);

  if (perFilament) {
    filaments = list(perFilament)
      .filter((g) => g > 0)
      .map((grams) => ({ grams, estimated: false }));
  } else if (totalGrams) {
    const g = list(totalGrams)[0];
    if (g > 0) filaments = [{ grams: g, estimated: false }];
  } else if (s3dGrams) {
    filaments = [{ grams: Number(s3dGrams), estimated: false }];
  }

  if (filaments.length === 0) {
    // Cura 5: volume in mm³ per extruder.
    const volumes = [...text.matchAll(/^;EXTRUDER_TRAIN\.(\d+)\.MATERIAL\.VOLUME_USED:\s*([\d.]+)/gim)]
      .map((m) => Number(m[2]))
      .filter((v) => v > 0);
    if (volumes.length > 0) {
      filaments = volumes.map((mm3) => ({
        grams: (mm3 / 1000) * DEFAULT_DENSITY,
        estimated: true,
      }));
    }
  }

  if (filaments.length === 0) {
    // Length only: Cura ";Filament used: 2.5m" and Orca/Prusa "filament used [mm]".
    const meters = find(text, /^;Filament used:\s*([^\r\n]+)/im);
    const mm = find(text, /;\s*(?:total )?filament (?:used|length) \[mm\]\s*[=:]\s*([^\r\n]+)/i);
    const lengths = meters
      ? [...meters.matchAll(/([\d.]+)\s*m\b/g)].map((m) => Number(m[1]) * 1000)
      : mm
        ? list(mm)
        : [];
    const d = Number(diameters?.split(/[;,]/)[0]) || DEFAULT_DIAMETER_MM;
    const rho = Number(densities?.split(/[;,]/)[0]) || DENSITY[types?.[0] ?? ""] || DEFAULT_DENSITY;
    filaments = lengths
      .filter((l) => l > 0)
      .map((l) => ({ grams: gramsFromLengthMm(l, rho, d), estimated: true }));
  }

  return { slicer, printSeconds, filaments: filaments.map(roundUse) };
}

const roundUse = (f: FilamentUse): FilamentUse => ({
  ...f,
  grams: Math.round(f.grams * 100) / 100,
});

/**
 * Reads `Metadata/slice_info.config` from a sliced Bambu Studio / OrcaSlicer
 * `.gcode.3mf`. Returns null when the XML has no plate summary.
 */
export function parseSliceInfoXml(xml: string): SliceInfo | null {
  const pairs = (s: string) =>
    Object.fromEntries([...s.matchAll(/(\w+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

  const plate = /<plate>([\s\S]*?)<\/plate>/.exec(xml)?.[1] ?? xml;
  let printSeconds: number | null = null;
  for (const m of plate.matchAll(/<metadata\s+([^>]*?)\/?>/g)) {
    const a = pairs(m[1]);
    if (a.key === "prediction" && Number(a.value) > 0) printSeconds = Number(a.value);
  }

  const filaments: FilamentUse[] = [];
  for (const m of plate.matchAll(/<filament\s+([^>]*?)\/?>/g)) {
    const a = pairs(m[1]);
    const grams = Number(a.used_g);
    if (grams > 0) filaments.push({ grams, estimated: false });
  }

  if (printSeconds === null && filaments.length === 0) return null;
  return { slicer: "Bambu Studio", printSeconds, filaments: filaments.map(roundUse) };
}

/** Splits seconds into the calculator's hour and minute fields. */
export function splitDuration(seconds: number) {
  let hours = Math.floor(seconds / 3600);
  let minutes = Math.round((seconds - hours * 3600) / 60);
  if (minutes === 60) {
    hours += 1;
    minutes = 0;
  }
  if (hours === 0 && minutes === 0 && seconds > 0) minutes = 1;
  return { hours, minutes };
}
