import { describe, expect, it } from "vitest";
import { parseDuration, parseGcode, parseSliceInfoXml, splitDuration } from "./parse";

describe("parseDuration", () => {
  it.each([
    ["1d 2h 3m 4s", 93784],
    ["2h 3m", 7380],
    ["12m 5s", 725],
    ["0 hours 12 minutes", 720],
    ["45s", 45],
  ])("reads %j", (text, seconds) => expect(parseDuration(text)).toBe(seconds));

  it("returns null without a unit", () => expect(parseDuration("soon")).toBeNull());
});

describe("splitDuration", () => {
  it("splits and rounds", () => {
    expect(splitDuration(3 * 3600 + 29 * 60 + 40)).toEqual({ hours: 3, minutes: 30 });
    expect(splitDuration(3599.9)).toEqual({ hours: 1, minutes: 0 });
    expect(splitDuration(20)).toEqual({ hours: 0, minutes: 1 });
  });
});

describe("parseGcode", () => {
  it("reads PrusaSlicer's footer", () => {
    const tail = `; filament used [mm] = 4021.87
; filament used [cm3] = 9.67
; filament used [g] = 12.00
; filament cost = 0.30
; total filament used [g] = 12.00
; estimated printing time (normal mode) = 1h 2m 3s
`;
    const r = parseGcode("; generated by PrusaSlicer 2.7.1", tail);
    expect(r.slicer).toBe("PrusaSlicer");
    expect(r.printSeconds).toBe(3723);
    expect(r.filaments).toEqual([{ grams: 12, estimated: false }]);
  });

  it("reads each filament of a multi-material OrcaSlicer print and skips unused slots", () => {
    const tail = `; filament used [g] = 12.34, 0.00, 5.6, 0.00
; estimated printing time (normal mode) = 2h 10m 0s`;
    const r = parseGcode("; generated by OrcaSlicer 2.1", tail);
    expect(r.filaments.map((f) => f.grams)).toEqual([12.34, 5.6]);
  });

  it("reads Bambu Studio's header block", () => {
    const head = `; HEADER_BLOCK_START
; BambuStudio 01.08.04.51
; model printing time: 52m 10s; total estimated time: 58m 31s
; total layer number: 100
; total filament length [mm] : 9876.5
; total filament weight [g] : 29.40
; HEADER_BLOCK_END`;
    const r = parseGcode(head, "");
    expect(r.slicer).toBe("Bambu Studio");
    expect(r.printSeconds).toBe(58 * 60 + 31);
    expect(r.filaments).toEqual([{ grams: 29.4, estimated: false }]);
  });

  it("estimates grams from Cura's filament length", () => {
    const head = `;FLAVOR:Marlin
;TIME:3600
;Filament used: 4.02187m
;Layer height: 0.2
;Generated with Cura_SteamEngine 5.4.0`;
    const r = parseGcode(head, "");
    expect(r.slicer).toBe("Cura");
    expect(r.printSeconds).toBe(3600);
    // 4021.87 mm of 1.75 mm filament at 1.24 g/cm³ is about 12 g.
    expect(r.filaments).toHaveLength(1);
    expect(r.filaments[0].estimated).toBe(true);
    expect(r.filaments[0].grams).toBeCloseTo(11.99, 1);
  });

  it("prefers Cura's material volume when present", () => {
    const head = `;TIME:600
;EXTRUDER_TRAIN.0.MATERIAL.VOLUME_USED:9670`;
    const r = parseGcode(head, "");
    expect(r.filaments[0].grams).toBeCloseTo(11.99, 1);
  });

  it("reads Simplify3D", () => {
    const head = `; G-Code generated by Simplify3D(R) Version 4.1.2
;   Build time: 0 hours 12 minutes
;   Filament length: 1234.5 mm (1.23 m)
;   Plastic weight: 3.48 g ( 0.01 lb )`;
    const r = parseGcode(head, "");
    expect(r.printSeconds).toBe(720);
    expect(r.filaments).toEqual([{ grams: 3.48, estimated: false }]);
  });

  it("returns nothing for a file without a summary", () => {
    const r = parseGcode("G28\nG1 X10 Y10 E1\n", "M84\n");
    expect(r).toEqual({ slicer: null, printSeconds: null, filaments: [] });
  });
});

describe("parseSliceInfoXml", () => {
  it("reads a sliced Bambu 3MF", () => {
    const xml = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header><header_item key="X-BBL-Client-Type" value="slicer"/></header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="3512"/>
    <metadata key="weight" value="17.95"/>
    <filament id="1" tray_info_idx="GFA00" type="PLA" color="#FFFFFF" used_m="3.5" used_g="12.34"/>
    <filament id="2" tray_info_idx="GFA00" type="PLA" color="#000000" used_m="1.8" used_g="5.61"/>
  </plate>
</config>`;
    const r = parseSliceInfoXml(xml);
    expect(r?.printSeconds).toBe(3512);
    expect(r?.filaments.map((f) => f.grams)).toEqual([12.34, 5.61]);
  });

  it("returns null when there is no plate summary", () => {
    expect(parseSliceInfoXml("<config></config>")).toBeNull();
  });
});
